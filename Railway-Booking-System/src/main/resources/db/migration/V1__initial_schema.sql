-- ============================================================================
-- V1__initial_schema.sql
-- Railway Booking System: Canonical Baseline Schema
-- Target Dialect: PostgreSQL 12+
-- Source of Truth: 14 JPA Entities in in.yograj.learnspringboot.railway_booking.entity
-- Incorporates Legacy Migrations 001, 002 (nullable stations) & 003 (idempotency unique constraint)
-- ============================================================================

-- ----------------------------------------------------------------------------
-- 1. Table: users
-- Entity: in.yograj.learnspringboot.railway_booking.entity.User
-- ----------------------------------------------------------------------------
CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL,
    full_name VARCHAR(255) NOT NULL,
    email VARCHAR(150) NOT NULL,
    phone_number VARCHAR(20),
    status VARCHAR(20),
    role VARCHAR(50) NOT NULL,
    created_at TIMESTAMP,
    password VARCHAR(255) NOT NULL,
    CONSTRAINT uk_users_username UNIQUE (username),
    CONSTRAINT uk_users_email UNIQUE (email)
);

-- ----------------------------------------------------------------------------
-- 2. Table: stations
-- Entity: in.yograj.learnspringboot.railway_booking.entity.Station
-- Note: city and state are NULLABLE (end-state of legacy migrations 001 and 002)
-- ----------------------------------------------------------------------------
CREATE TABLE stations (
    station_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    station_code VARCHAR(20) NOT NULL,
    station_name VARCHAR(120) NOT NULL,
    city VARCHAR(120),
    state VARCHAR(120),
    CONSTRAINT uk_stations_station_code UNIQUE (station_code)
);

-- ----------------------------------------------------------------------------
-- 3. Table: trains
-- Entity: in.yograj.learnspringboot.railway_booking.entity.Train
-- ----------------------------------------------------------------------------
CREATE TABLE trains (
    train_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_number VARCHAR(30) NOT NULL,
    train_name VARCHAR(120) NOT NULL,
    status VARCHAR(30) NOT NULL,
    CONSTRAINT uk_trains_train_number UNIQUE (train_number)
);

-- ----------------------------------------------------------------------------
-- 4. Table: coaches
-- Entity: in.yograj.learnspringboot.railway_booking.entity.Coach
-- ----------------------------------------------------------------------------
CREATE TABLE coaches (
    coach_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_id BIGINT NOT NULL,
    coach_number VARCHAR(20) NOT NULL,
    coach_type VARCHAR(30) NOT NULL,
    seat_capacity INT NOT NULL,
    status VARCHAR(30) NOT NULL,
    CONSTRAINT fk_coaches_train FOREIGN KEY (train_id) REFERENCES trains (train_id),
    CONSTRAINT uk_train_coach_number UNIQUE (train_id, coach_number)
);

-- ----------------------------------------------------------------------------
-- 5. Table: seats
-- Entity: in.yograj.learnspringboot.railway_booking.entity.Seat
-- ----------------------------------------------------------------------------
CREATE TABLE seats (
    seat_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    coach_id BIGINT NOT NULL,
    seat_number INT NOT NULL,
    seat_type VARCHAR(30) NOT NULL,
    status VARCHAR(30) NOT NULL,
    CONSTRAINT fk_seats_coach FOREIGN KEY (coach_id) REFERENCES coaches (coach_id),
    CONSTRAINT uk_coach_seat_number UNIQUE (coach_id, seat_number)
);

-- ----------------------------------------------------------------------------
-- 6. Table: train_routes
-- Entity: in.yograj.learnspringboot.railway_booking.entity.TrainRoute
-- ----------------------------------------------------------------------------
CREATE TABLE train_routes (
    train_route_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_id BIGINT NOT NULL,
    route_name VARCHAR(100) NOT NULL,
    CONSTRAINT fk_train_routes_train FOREIGN KEY (train_id) REFERENCES trains (train_id),
    CONSTRAINT uk_train_route_name UNIQUE (train_id, route_name)
);

-- ----------------------------------------------------------------------------
-- 7. Table: train_stops
-- Entity: in.yograj.learnspringboot.railway_booking.entity.TrainStop
-- ----------------------------------------------------------------------------
CREATE TABLE train_stops (
    train_stop_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_route_id BIGINT NOT NULL,
    station_id BIGINT NOT NULL,
    stop_sequence INT NOT NULL,
    arrival_time TIME,
    departure_time TIME,
    day_offset INT NOT NULL,
    CONSTRAINT fk_train_stops_route FOREIGN KEY (train_route_id) REFERENCES train_routes (train_route_id),
    CONSTRAINT fk_train_stops_station FOREIGN KEY (station_id) REFERENCES stations (station_id),
    CONSTRAINT uk_route_stop_sequence UNIQUE (train_route_id, stop_sequence)
);

CREATE INDEX idx_train_stop_station ON train_stops (station_id);

-- ----------------------------------------------------------------------------
-- 8. Table: journeys
-- Entity: in.yograj.learnspringboot.railway_booking.entity.Journey
-- ----------------------------------------------------------------------------
CREATE TABLE journeys (
    journey_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    train_id BIGINT NOT NULL,
    train_route_id BIGINT,
    from_station_id BIGINT NOT NULL,
    to_station_id BIGINT NOT NULL,
    journey_date DATE NOT NULL,
    departure_time TIME NOT NULL,
    arrival_time TIME NOT NULL,
    CONSTRAINT fk_journeys_train FOREIGN KEY (train_id) REFERENCES trains (train_id),
    CONSTRAINT fk_journeys_route FOREIGN KEY (train_route_id) REFERENCES train_routes (train_route_id),
    CONSTRAINT fk_journeys_from_station FOREIGN KEY (from_station_id) REFERENCES stations (station_id),
    CONSTRAINT fk_journeys_to_station FOREIGN KEY (to_station_id) REFERENCES stations (station_id)
);

CREATE INDEX idx_journey_route_date ON journeys (from_station_id, to_station_id, journey_date);
CREATE INDEX idx_journey_train_date ON journeys (train_id, journey_date);

-- ----------------------------------------------------------------------------
-- 9. Table: journey_stops
-- Entity: in.yograj.learnspringboot.railway_booking.entity.JourneyStop
-- ----------------------------------------------------------------------------
CREATE TABLE journey_stops (
    journey_stop_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journey_id BIGINT NOT NULL,
    train_stop_id BIGINT,
    station_id BIGINT NOT NULL,
    stop_sequence INT NOT NULL,
    arrival_at TIMESTAMP,
    departure_at TIMESTAMP,
    CONSTRAINT fk_journey_stops_journey FOREIGN KEY (journey_id) REFERENCES journeys (journey_id),
    CONSTRAINT fk_journey_stops_train_stop FOREIGN KEY (train_stop_id) REFERENCES train_stops (train_stop_id),
    CONSTRAINT fk_journey_stops_station FOREIGN KEY (station_id) REFERENCES stations (station_id),
    CONSTRAINT uk_journey_stop_sequence UNIQUE (journey_id, stop_sequence)
);

CREATE INDEX idx_journey_stop_station ON journey_stops (station_id, journey_id);

-- ----------------------------------------------------------------------------
-- 10. Table: journey_seat_inventory
-- Entity: in.yograj.learnspringboot.railway_booking.entity.JourneySeatInventory
-- ----------------------------------------------------------------------------
CREATE TABLE journey_seat_inventory (
    inventory_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    journey_id BIGINT NOT NULL,
    coach_id BIGINT NOT NULL,
    seat_id BIGINT NOT NULL,
    hold_user_id BIGINT,
    status VARCHAR(30) NOT NULL,
    hold_expires_at TIMESTAMP,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_inventory_journey FOREIGN KEY (journey_id) REFERENCES journeys (journey_id),
    CONSTRAINT fk_inventory_coach FOREIGN KEY (coach_id) REFERENCES coaches (coach_id),
    CONSTRAINT fk_inventory_seat FOREIGN KEY (seat_id) REFERENCES seats (seat_id),
    CONSTRAINT fk_inventory_hold_user FOREIGN KEY (hold_user_id) REFERENCES users (user_id),
    CONSTRAINT uk_journey_coach_seat UNIQUE (journey_id, coach_id, seat_id)
);

CREATE INDEX idx_inventory_journey_status ON journey_seat_inventory (journey_id, status);
CREATE INDEX idx_inventory_hold_expiry ON journey_seat_inventory (hold_expires_at);

-- ----------------------------------------------------------------------------
-- 11. Table: seat_allocations
-- Entity: in.yograj.learnspringboot.railway_booking.entity.SeatAllocation
-- ----------------------------------------------------------------------------
CREATE TABLE seat_allocations (
    seat_allocation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inventory_id BIGINT NOT NULL,
    boarding_journey_stop_id BIGINT NOT NULL,
    alighting_journey_stop_id BIGINT NOT NULL,
    hold_user_id BIGINT NOT NULL,
    status VARCHAR(30) NOT NULL,
    hold_expires_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_allocation_inventory FOREIGN KEY (inventory_id) REFERENCES journey_seat_inventory (inventory_id),
    CONSTRAINT fk_allocation_boarding_stop FOREIGN KEY (boarding_journey_stop_id) REFERENCES journey_stops (journey_stop_id),
    CONSTRAINT fk_allocation_alighting_stop FOREIGN KEY (alighting_journey_stop_id) REFERENCES journey_stops (journey_stop_id),
    CONSTRAINT fk_allocation_hold_user FOREIGN KEY (hold_user_id) REFERENCES users (user_id)
);

CREATE INDEX idx_allocation_inventory_status ON seat_allocations (inventory_id, status);
CREATE INDEX idx_allocation_hold_expiry ON seat_allocations (hold_expires_at);

-- ----------------------------------------------------------------------------
-- 12. Table: bookings
-- Entity: in.yograj.learnspringboot.railway_booking.entity.Booking
-- ----------------------------------------------------------------------------
CREATE TABLE bookings (
    booking_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    journey_id BIGINT NOT NULL,
    coach_id BIGINT NOT NULL,
    seat_id BIGINT NOT NULL,
    journey_seat_inventory_id BIGINT NOT NULL,
    seat_allocation_id BIGINT,
    booking_ref VARCHAR(40) NOT NULL,
    booking_status VARCHAR(40) NOT NULL,
    payment_status VARCHAR(40) NOT NULL,
    amount NUMERIC(10, 2),
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_bookings_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT fk_bookings_journey FOREIGN KEY (journey_id) REFERENCES journeys (journey_id),
    CONSTRAINT fk_bookings_coach FOREIGN KEY (coach_id) REFERENCES coaches (coach_id),
    CONSTRAINT fk_bookings_seat FOREIGN KEY (seat_id) REFERENCES seats (seat_id),
    CONSTRAINT fk_bookings_inventory FOREIGN KEY (journey_seat_inventory_id) REFERENCES journey_seat_inventory (inventory_id),
    CONSTRAINT fk_bookings_seat_allocation FOREIGN KEY (seat_allocation_id) REFERENCES seat_allocations (seat_allocation_id),
    CONSTRAINT uk_bookings_booking_ref UNIQUE (booking_ref),
    CONSTRAINT uk_bookings_seat_allocation UNIQUE (seat_allocation_id)
);

-- ----------------------------------------------------------------------------
-- 13. Table: payment_transactions
-- Entity: in.yograj.learnspringboot.railway_booking.entity.PaymentTransaction
-- Note: Includes uk_payment_booking_idempotency (end-state of legacy migration 003)
-- ----------------------------------------------------------------------------
CREATE TABLE payment_transactions (
    payment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    booking_ref VARCHAR(40) NOT NULL,
    transaction_ref VARCHAR(64) NOT NULL,
    payment_method VARCHAR(50) NOT NULL,
    amount NUMERIC(10, 2) NOT NULL,
    status VARCHAR(30) NOT NULL,
    failure_reason VARCHAR(255),
    idempotency_key VARCHAR(64),
    simulate_failure BOOLEAN,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_payments_booking FOREIGN KEY (booking_id) REFERENCES bookings (booking_id),
    CONSTRAINT uk_payment_transaction_ref UNIQUE (transaction_ref),
    CONSTRAINT uk_payment_booking_idempotency UNIQUE (booking_ref, idempotency_key)
);

CREATE INDEX idx_payment_booking_ref ON payment_transactions (booking_ref);
CREATE INDEX idx_payment_transaction_ref ON payment_transactions (transaction_ref);

-- ----------------------------------------------------------------------------
-- 14. Table: refresh_tokens
-- Entity: in.yograj.learnspringboot.railway_booking.entity.RefreshToken
-- Note: expires_at is TIMESTAMPTZ (mapped from java.time.Instant)
-- ----------------------------------------------------------------------------
CREATE TABLE refresh_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token VARCHAR(512) NOT NULL,
    user_id BIGINT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked BOOLEAN NOT NULL,
    CONSTRAINT fk_refresh_tokens_user FOREIGN KEY (user_id) REFERENCES users (user_id),
    CONSTRAINT uk_refresh_tokens_token UNIQUE (token)
);
