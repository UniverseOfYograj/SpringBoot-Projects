-- Step 1: Create passengers table
CREATE TABLE IF NOT EXISTS passengers (
    passenger_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    seat_allocation_id BIGINT NOT NULL,
    seat_id BIGINT NOT NULL,
    coach_id BIGINT NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    age INT NOT NULL,
    gender VARCHAR(20) NOT NULL,
    berth_preference VARCHAR(30),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_passengers_booking FOREIGN KEY (booking_id) REFERENCES bookings (booking_id) ON DELETE CASCADE,
    CONSTRAINT fk_passengers_seat_allocation FOREIGN KEY (seat_allocation_id) REFERENCES seat_allocations (seat_allocation_id),
    CONSTRAINT fk_passengers_seat FOREIGN KEY (seat_id) REFERENCES seats (seat_id),
    CONSTRAINT fk_passengers_coach FOREIGN KEY (coach_id) REFERENCES coaches (coach_id),
    CONSTRAINT uk_passengers_seat_allocation UNIQUE (seat_allocation_id),
    CONSTRAINT uk_passengers_booking_seat UNIQUE (booking_id, seat_id),
    CONSTRAINT chk_passenger_age CHECK (age >= 1 AND age <= 125),
    CONSTRAINT chk_passenger_name CHECK (LENGTH(TRIM(full_name)) >= 2)
);

-- Step 2: Create performance indexes
CREATE INDEX IF NOT EXISTS idx_passengers_booking_id ON passengers (booking_id);
CREATE INDEX IF NOT EXISTS idx_passengers_seat_allocation_id ON passengers (seat_allocation_id);

-- Step 3: Backfill passenger records for any pre-existing single-seat bookings
INSERT INTO passengers (booking_id, seat_allocation_id, seat_id, coach_id, full_name, age, gender, berth_preference, created_at)
SELECT 
    b.booking_id,
    b.seat_allocation_id,
    b.seat_id,
    b.coach_id,
    COALESCE(NULLIF(TRIM(u.full_name), ''), u.username, 'Passenger'),
    30,
    'MALE',
    NULL,
    b.created_at
FROM bookings b
JOIN users u ON b.user_id = u.user_id
WHERE b.seat_allocation_id IS NOT NULL
  AND NOT EXISTS (
      SELECT 1 FROM passengers p WHERE p.seat_allocation_id = b.seat_allocation_id
  );
